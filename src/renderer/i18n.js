const RAT_LANG_ORDER = [
  { v: 'auto', k: 'lang.auto' },
  { v: 'en', k: 'lang.en' },
  { v: 'zh-CN', k: 'lang.zh-CN' },
  { v: 'ja', k: 'lang.ja' },
  { v: 'ko', k: 'lang.ko' },
];

let RAT_LANG = 'en';

function ratDetectLangByTimezone() {
  try {
    const tz = (Intl.DateTimeFormat().resolvedOptions().timeZone || '').toString();
    if (/^Asia\/(Shanghai|Chongqing|Harbin|Urumqi|Hong_Kong|Macau|Taipei)/.test(tz)) return 'zh-CN';
    if (tz === 'Asia/Tokyo') return 'ja';
    if (tz === 'Asia/Seoul') return 'ko';
  } catch {}
  return 'en';
}

// pref: 'auto' | 'en' | 'zh-CN' | 'ja' | 'ko'
// 'auto' 按当前时区推断；其余直接采用；未知值退回英语（默认）。
function ratResolveLang(pref) {
  if (!pref || pref === 'auto') return ratDetectLangByTimezone();
  if (pref === 'en' || RAT_DICTS[pref]) return pref;
  return 'en';
}

function t(key, params) {
  if (key == null) return key;
  let out;
  const dict = RAT_DICTS[RAT_LANG];
  if (dict && Object.prototype.hasOwnProperty.call(dict, key)) {
    out = dict[key];
  } else {
    out = key; // 英文 key 直接作为默认文案
  }
  if (params) {
    out = String(out).replace(/\{(\w+)\}/g, (m, n) => (params[n] !== undefined ? params[n] : m));
  }
  return out;
}

// 把 [data-i18n] 元素的文本、[data-i18n-title] 的 title、[data-i18n-attr] 指定属性翻译成当前语言。
function applyStaticI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const val = t(key);
    if (attr === 'title') el.setAttribute('title', val);
    else if (attr === 'placeholder') el.setAttribute('placeholder', val);
    else if (attr === 'html') el.innerHTML = val;
    else el.textContent = val;
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}

// 导出到全局，供 app.js 使用
window.RAT_I18N = {
  t,
  applyStaticI18n,
  ratResolveLang,
  ratDetectLangByTimezone,
  getLang: () => RAT_LANG,
  setLang: (code) => { RAT_LANG = code; },
  order: RAT_LANG_ORDER,
};
